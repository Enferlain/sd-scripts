from dataclasses import dataclass, field
from typing import Optional, List, Union
from .deepspeed import DeepSpeedConfig

@dataclass
class TrainingConfig:
    output_dir: Optional[str] = field(default=None, metadata={"help": "directory to output trained model"})
    output_name: Optional[str] = field(default=None, metadata={"help": "base name of trained model file"})
    huggingface_repo_id: Optional[str] = field(default=None, metadata={"help": "huggingface repo name to upload"})
    huggingface_repo_type: Optional[str] = field(default=None, metadata={"help": "huggingface repo type to upload"})
    huggingface_path_in_repo: Optional[str] = field(default=None, metadata={"help": "huggingface model path to upload files"})
    huggingface_token: Optional[str] = field(default=None, metadata={"help": "huggingface token"})
    huggingface_repo_visibility: Optional[str] = field(default=None, metadata={"help": "huggingface repository visibility"})
    save_state_to_huggingface: bool = field(default=False, metadata={"help": "save state to huggingface"})
    resume_from_huggingface: bool = field(default=False, metadata={"help": "resume from huggingface"})
    async_upload: bool = field(default=False, metadata={"help": "upload to huggingface asynchronously"})
    save_precision: Optional[str] = field(default=None, metadata={"help": "precision in saving", "choices": [None, "float", "fp16", "bf16"]})
    save_every_n_epochs: Optional[int] = field(default=None, metadata={"help": "save checkpoint every N epochs"})
    save_every_n_steps: Optional[int] = field(default=None, metadata={"help": "save checkpoint every N steps"})
    save_n_epoch_ratio: Optional[int] = field(default=None, metadata={"help": "save checkpoint N epoch ratio"})
    save_last_n_epochs: Optional[int] = field(default=None, metadata={"help": "save last N checkpoints when saving every N epochs"})
    save_last_n_epochs_state: Optional[int] = field(default=None, metadata={"help": "save last N checkpoints of state"})
    save_last_n_steps: Optional[int] = field(default=None, metadata={"help": "save checkpoints until N steps elapsed"})
    save_last_n_steps_state: Optional[int] = field(default=None, metadata={"help": "save states until N steps elapsed"})
    save_state: bool = field(default=False, metadata={"help": "save training state additionally"})
    save_state_on_train_end: bool = field(default=False, metadata={"help": "save training state on train end"})
    resume: Optional[str] = field(default=None, metadata={"help": "saved state to resume training"})
    train_batch_size: int = field(default=1, metadata={"help": "batch size for training"})
    max_token_length: Optional[int] = field(default=None, metadata={"help": "max token length of text encoder", "choices": [None, 150, 225]})
    mem_eff_attn: bool = field(default=False, metadata={"help": "use memory efficient attention for CrossAttention"})
    torch_compile: bool = field(default=False, metadata={"help": "use torch.compile"})
    dynamo_backend: str = field(default="inductor", metadata={"help": "dynamo backend type"})
    xformers: bool = field(default=False, metadata={"help": "use xformers for CrossAttention"})
    sdpa: bool = field(default=False, metadata={"help": "use sdpa for CrossAttention"})
    vae: Optional[str] = field(default=None, metadata={"help": "path to checkpoint of vae to replace"})
    max_train_steps: int = field(default=1600, metadata={"help": "training steps"})
    max_train_epochs: Optional[int] = field(default=None, metadata={"help": "training epochs"})
    max_data_loader_n_workers: int = field(default=8, metadata={"help": "max num workers for DataLoader"})
    persistent_data_loader_workers: bool = field(default=False, metadata={"help": "persistent DataLoader workers"})
    seed: Optional[int] = field(default=None, metadata={"help": "random seed for training"})
    gradient_checkpointing: bool = field(default=False, metadata={"help": "enable gradient checkpointing"})
    gradient_accumulation_steps: int = field(default=1, metadata={"help": "Number of updates steps to accumulate before performing a backward/update pass"})
    mixed_precision: str = field(default="no", metadata={"help": "use mixed precision", "choices": ["no", "fp16", "bf16"]})
    full_fp16: bool = field(default=False, metadata={"help": "fp16 training including gradients"})
    full_bf16: bool = field(default=False, metadata={"help": "bf16 training including gradients"})
    fp8_base: bool = field(default=False, metadata={"help": "use fp8 for base model"})
    ddp_timeout: Optional[int] = field(default=None, metadata={"help": "DDP timeout"})
    ddp_gradient_as_bucket_view: bool = field(default=False, metadata={"help": "enable gradient_as_bucket_view for DDP"})
    ddp_static_graph: bool = field(default=False, metadata={"help": "enable static_graph for DDP"})
    clip_skip: Optional[int] = field(default=None, metadata={"help": "use output of nth layer from back of text encoder"})
    logging_dir: Optional[str] = field(default=None, metadata={"help": "enable logging and output TensorBoard log to this directory"})
    log_with: Optional[str] = field(default=None, metadata={"help": "what logging tool(s) to use", "choices": ["tensorboard", "wandb", "all"]})
    log_prefix: Optional[str] = field(default=None, metadata={"help": "add prefix for each log directory"})
    log_tracker_name: Optional[str] = field(default=None, metadata={"help": "name of tracker to use for logging"})
    wandb_run_name: Optional[str] = field(default=None, metadata={"help": "The name of the specific wandb session"})
    log_tracker_config: Optional[str] = field(default=None, metadata={"help": "path to tracker config file to use for logging"})
    wandb_api_key: Optional[str] = field(default=None, metadata={"help": "specify WandB API key to log in before starting training"})
    log_config: bool = field(default=False, metadata={"help": "log training configuration"})
    console_log_level: Optional[str] = field(default=None, metadata={"help": "Set the logging level"})
    console_log_file: Optional[str] = field(default=None, metadata={"help": "Log to a file instead of stderr"})
    console_log_simple: bool = field(default=False, metadata={"help": "Simple log output"})
    noise_offset: Optional[float] = field(default=None, metadata={"help": "enable noise offset with this value"})
    noise_offset_random_strength: bool = field(default=False, metadata={"help": "use random strength between 0~noise_offset for noise offset"})
    multires_noise_iterations: Optional[int] = field(default=None, metadata={"help": "enable multires noise with this number of iterations"})
    ip_noise_gamma: Optional[float] = field(default=None, metadata={"help": "enable input perturbation noise"})
    ip_noise_gamma_random_strength: bool = field(default=False, metadata={"help": "Use random strength between 0~ip_noise_gamma for input perturbation noise"})
    multires_noise_discount: float = field(default=0.3, metadata={"help": "set discount value for multires noise"})
    adaptive_noise_scale: Optional[float] = field(default=None, metadata={"help": "add `latent mean absolute value * this value` to noise_offset"})
    zero_terminal_snr: bool = field(default=False, metadata={"help": "fix noise scheduler betas to enforce zero terminal SNR"})
    min_timestep: Optional[int] = field(default=None, metadata={"help": "set minimum time step for U-Net training"})
    max_timestep: Optional[int] = field(default=None, metadata={"help": "set maximum time step for U-Net training"})
    dynamic_timestep_schedule: Optional[str] = field(default=None, metadata={"help": "A list of lists defining a dynamic timestep schedule"})
    loss_type: str = field(default="l2", metadata={"help": "The type of loss function to use", "choices": ["l1", "l2", "huber", "smooth_l1"]})
    huber_schedule: str = field(default="snr", metadata={"help": "The scheduling method for Huber loss", "choices": ["constant", "exponential", "snr"]})
    huber_c: float = field(default=0.1, metadata={"help": "The Huber loss decay parameter"})
    huber_scale: float = field(default=1.0, metadata={"help": "The Huber loss scale parameter"})
    loss_scale: float = field(default=1.0, metadata={"help": "A scale factor for certain loss types"})
    lowram: bool = field(default=False, metadata={"help": "enable low RAM optimization"})
    highvram: bool = field(default=False, metadata={"help": "disable low VRAM optimization"})
    sample_every_n_steps: Optional[int] = field(default=None, metadata={"help": "generate sample images every N steps"})
    sample_at_first: bool = field(default=False, metadata={"help": "generate sample images before training"})
    sample_every_n_epochs: Optional[int] = field(default=None, metadata={"help": "generate sample images every N epochs"})
    sample_prompts: Optional[str] = field(default=None, metadata={"help": "file for prompts to generate sample images"})
    sample_sampler: str = field(default="ddim", metadata={"help": "sampler (scheduler) type for sample images"})
    config_file: Optional[str] = field(default=None, metadata={"help": "using .toml instead of args to pass hyperparameter"})
    output_config: bool = field(default=False, metadata={"help": "output command line args to given .toml file"})
    prior_loss_weight: float = field(default=1.0, metadata={"help": "loss weight for regularization images"})
    timestep_sampling: str = field(default="uniform", metadata={"help": "Method to sample timesteps"})
    sigmoid_scale: float = field(default=1.0, metadata={"help": "Scale factor for sigmoid timestep sampling"})
    discrete_flow_shift: float = field(default=1.0, metadata={"help": "Discrete flow shift for the Euler Discrete Scheduler"})
    mix_adaptive_start_p: float = field(default=0.85)
    mix_adaptive_end_p: float = field(default=0.35)
    mix_adaptive_fixed_p: Optional[float] = field(default=None)
    mix_adaptive_anneal: str = field(default="cosine")
    mix_adaptive_bins: int = field(default=32)
    mix_adaptive_ema_beta: float = field(default=0.9)
    mix_adaptive_small_t_frac: float = field(default=0.15)
    mix_adaptive_small_t_cap: float = field(default=0.6)
    mix_adaptive_temperature: float = field(default=0.5)
    mix_adaptive_prior_weight: float = field(default=0.2)
    mix_adaptive_min_prob: float = field(default=1e-4)
    mix_adaptive_warmup_steps: int = field(default=2000)
    mix_adaptive_prior_bias: float = field(default=0.8)
    mix_adaptive_entropy_floor_ratio: float = field(default=0.7)
    mix_adaptive_uniform_mix_when_low_entropy: float = field(default=0.1)
    mix_adaptive_prior_mu: float = field(default=0.0)
    mix_adaptive_prior_sigma: float = field(default=1.0)
    mix_adaptive_center_mu: float = field(default=0.0)
    mix_adaptive_half_width: float = field(default=0.8)
    mix_adaptive_widen_to: float = field(default=2.5)
    mix_adaptive_max_train_steps: int = field(default=2000)
    mix_adaptive_cap_max_t: int = field(default=950)
    disable_cuda_reduced_precision_operations: bool = field(default=False)
    enable_cuda_reduced_precision_operations: bool = field(default=False)
    loss_multiplier: Optional[float] = field(default=None)
    save_model_as: Optional[str] = field(default=None, metadata={"help": "format to save the model", "choices": [None, "ckpt", "safetensors", "diffusers", "diffusers_safetensors"]})
    use_safetensors: bool = field(default=False, metadata={"help": "use safetensors format to save"})
    deepspeed: DeepSpeedConfig = field(default_factory=DeepSpeedConfig)

    def __post_init__(self):
        if self.adaptive_noise_scale is not None and self.noise_offset is None:
            raise ValueError("adaptive_noise_scale requires noise_offset")

        if self.sample_every_n_epochs is not None and self.sample_every_n_epochs <= 0:
            self.sample_every_n_epochs = None

        if self.sample_every_n_steps is not None and self.sample_every_n_steps <= 0:
            self.sample_every_n_steps = None
